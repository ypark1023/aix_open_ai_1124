import os
from dotenv import load_dotenv
from pathlib import Path
import openai
from openai import OpenAI

BASE_DIR = Path(__file__).resolve().parent.parent
envFile = BASE_DIR / '.env'

load_dotenv()
# print(os.getenv('open_ai_key'))

api_key = os.getenv('open_ai_key')
client = OpenAI(api_key=api_key)

message1 = input('초등학교 수업자료 설명>>')


try:
    print('API 연결을 시작합니다.')

    response = client.responses.create(
        model='gpt-5.6',
        instructions="""
            당신은 초등학교 교사입니다.
            [학습목표], [학습내용], [학습정리], [퀴즈] 순서로 알려주세요.
            아이들이 흥미를 느낄 수 있게 쉽고 재밌게 구성해주세요.
            """,
        input=f'{message1}에 대해 제안해주세요',
        max_output_tokens=1000,
    )
    # API 응답 텍스트 추출
    result = response.output_text.strip()

    if not result:
        raise RuntimeError('api 응답에 표시할 텍스트 없음')
    print('-' * 40)
    print(result)
    
except openai.APIConnectionError as error:
    print(f'api 연결에러 확인 요망: {error}')

except openai.RateLimitError as error:
    print(f'api 요청한도 확인 요망: {error}')

except openai.APIError as error:
    print(f'api 요청 실패: {error}')



